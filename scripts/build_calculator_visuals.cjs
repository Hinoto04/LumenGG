/* Rebuild the same passive state adapter for React Native and the opt-in web UI. */
const fs = require("fs");
const path = require("path");
const root = path.resolve(__dirname, "..");
for (const file of [
  "calculator-passives.json",
  "calculator-passive-art.json",
  "calculator-passive-visuals.json",
  "calculator-symbol-art.json",
  "calculator-clean-icons.json",
]) {
  fs.copyFileSync(
    path.join(root, "LumenGG/content", file),
    path.join(root, "mobile/src", file),
  );
}
const esbuild = require(path.join(root, "mobile/node_modules/esbuild"));
esbuild.buildSync({
  entryPoints: [path.join(root, "mobile/src/calculator-visual-model.ts")],
  bundle: true,
  format: "iife",
  globalName: "CalculatorVisualModel",
  target: "es2021",
  outfile: path.join(root, "LumenGG/static/v2/calculator-visual-model.js"),
});
const art = JSON.parse(
  fs.readFileSync(
    path.join(root, "LumenGG/content/calculator-passive-art.json"),
  ),
);
const lines = [
  "// Generated by scripts/build_calculator_visuals.cjs.",
  "export const passiveImages: Record<string, number> = {",
];
for (const [key, item] of Object.entries(art)) {
  fs.copyFileSync(
    path.join(
      root,
      "LumenGG/static/v2/calculator-character/passives",
      item.file,
    ),
    path.join(root, "mobile/assets/calculator-character/passives", item.file),
  );
  lines.push(
    "  " +
      key +
      ': require("../assets/calculator-character/passives/' +
      item.file +
      '"),',
  );
}
lines.push("};", "");
fs.writeFileSync(
  path.join(root, "mobile/src/calculator-passive-images.ts"),
  lines.join("\n"),
);
console.log("Shared visual adapter and original card assets packaged.");
esbuild.buildSync({
 entryPoints:[path.join(root,"mobile/src/calculator-passive-queue.ts")],bundle:true,format:"iife",globalName:"CalculatorPassiveInputModel",
 outfile:path.join(root,"LumenGG/static/v2/calculator-passive-input-model.js"),target:"es2021",minify:true,
});
esbuild.buildSync({
 entryPoints:[path.join(root,"mobile/src/calculator-shield.ts")],bundle:true,format:"iife",globalName:"CalculatorShieldModel",
 outfile:path.join(root,"LumenGG/static/v2/calculator-shield-model.js"),target:"es2021",minify:true,
});
require(path.join(root,"mobile/node_modules/esbuild")).buildSync({
 entryPoints:[path.join(root,"mobile/src/calculator-appearance.ts")],bundle:true,format:"iife",globalName:"CalculatorAppearanceModel",
 outfile:path.join(root,"LumenGG/static/v2/calculator-appearance-model.js"),minify:true,
});
const symbols = path.join(root, 'LumenGG/static/v2/calculator-character/symbols');
const nativeSymbols = path.join(root, 'mobile/assets/calculator-character/symbols');
fs.mkdirSync(nativeSymbols, {recursive:true});
const symbolLines = ['// Generated by scripts/build_calculator_visuals.cjs.', 'export const passiveSymbols: Record<string, number> = {'];
const rasterArt = require(path.join(root,"LumenGG/content/calculator-symbol-art.json"));
for (const [key,asset] of Object.entries(rasterArt)) {
  const file=asset.file;
  fs.copyFileSync(path.join(symbols,file),path.join(nativeSymbols,file));
  // Active/idle share the exact image; UI brightness expresses state.
  for(const variant of [key,key+"-idle"])
    symbolLines.push(JSON.stringify(variant)+': require("../assets/calculator-character/symbols/'+file+'"),');
}
symbolLines.push('};','');
fs.writeFileSync(path.join(root,'mobile/src/calculator-symbol-images.ts'),symbolLines.join('\n'));
