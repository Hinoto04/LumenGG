/* Package approved raster masters and original card crops for the clean HUD.
 * Only crop, scale, pad and round card corners; never redraw emblems here. */
const fs=require('fs'),path=require('path'),crypto=require('crypto'),sharp=require('sharp');
const root=path.resolve(__dirname,'..');
const web=path.join(root,'LumenGG/static/v2/calculator-character/clean');
const app=path.join(root,'mobile/assets/calculator-character/clean');
const manifest=require(path.join(root,'LumenGG/content/calculator-clean-icons.json'));
const transparent={r:0,g:0,b:0,alpha:0};
const sha=buffer=>crypto.createHash('sha256').update(buffer).digest('hex');
async function alphaBounds(buffer){
 const {data,info}=await sharp(buffer).ensureAlpha().raw().toBuffer({resolveWithObject:true});
 let left=info.width,top=info.height,right=-1,bottom=-1;
 for(let y=0;y<info.height;y++)for(let x=0;x<info.width;x++)if(data[(y*info.width+x)*4+3]){
  left=Math.min(left,x);top=Math.min(top,y);right=Math.max(right,x);bottom=Math.max(bottom,y);
 }
 if(right<0)throw new Error('Empty raster asset');
 return {left,top,width:right-left+1,height:bottom-top+1};
}
(async()=>{
 fs.mkdirSync(app,{recursive:true});
 const lines=['// Generated by scripts/build_calculator_clean.cjs.','export const passiveCleanImages: Record<string, number> = {'];
 const report=[];
 for(const [key,item] of Object.entries(manifest)){
  const source=fs.readFileSync(path.join(root,item.source));
  let image=sharp(source).ensureAlpha();
  if(item.crop){const [left,top,width,height]=item.crop;image=image.extract({left,top,width,height});}
  if(item.trim_alpha)image=image.extract(await alphaBounds(source));
  const [width,height]=item.canvas||[256,256],padding=item.kind==='card'?8:12;
  const contentWidth=width-padding*2,contentHeight=height-padding*2;
  let content=await image.resize(contentWidth,contentHeight,{fit:'contain',background:transparent}).png().toBuffer();
  if(item.kind==='card'){
   const mask=Buffer.from(`<svg width="${contentWidth}" height="${contentHeight}"><rect width="100%" height="100%" rx="14" fill="white"/></svg>`);
   content=await sharp(content).composite([{input:mask,blend:'dest-in'}]).png().toBuffer();
  }
  const buffer=await sharp(content).extend({top:padding,bottom:padding,left:padding,right:padding,background:transparent}).png().toBuffer();
  fs.writeFileSync(path.join(web,item.file),buffer);fs.writeFileSync(path.join(app,item.file),buffer);
  lines.push(JSON.stringify(key)+': require("../assets/calculator-character/clean/'+item.file+'"),');
  const meta=await sharp(buffer).metadata(),bounds=await alphaBounds(buffer);
  if(!meta.hasAlpha||bounds.left<8||bounds.top<8||bounds.left+bounds.width>width-8||bounds.top+bounds.height>height-8)throw new Error('Clipped icon '+key);
  report.push({key,...item,width,height,hasAlpha:meta.hasAlpha,bounds,bytes:buffer.length,sha256:sha(buffer),source_sha256:sha(source),web_app_identical:buffer.equals(fs.readFileSync(path.join(app,item.file)))});
 }
 lines.push('};','');fs.writeFileSync(path.join(root,'mobile/src/calculator-clean-images.ts'),lines.join('\n'));
 const provenance={date:'2026-10-20',mode:'built-in image_gen + approved original-card crops',prompts:'artifacts/calculator-character/clean-sources/imagegen-prompts-v2.json',assets:manifest,previous:'LUCIDE-SOURCE.json (historical comparison only; not used by runtime)'};
 fs.writeFileSync(path.join(web,'SOURCE.json'),JSON.stringify(provenance,null,2)+'\n');
 fs.writeFileSync(path.join(root,'artifacts/calculator-character/clean-v2-assets-report.json'),JSON.stringify({date:'2026-10-20',count:report.length,generated:14,original_card_crops:9,reused_restored_card:1,assets:report},null,2)+'\n');
 console.log(report.length+' clean raster icons packaged identically for web and app.');
})().catch(e=>{console.error(e);process.exit(1)});
